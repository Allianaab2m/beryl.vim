-- lua/beryl/palette.lua から extras/ 以下のテーマを生成する
-- 使い方: nvim -l scripts/build.lua（リポジトリのルートで実行）
package.path = "./lua/?.lua;" .. package.path
local p = require("beryl.palette")

local header = "beryl colorscheme. Generated by scripts/build.lua from lua/beryl/palette.lua; do not edit."

local targets = {}

targets["extras/ghostty/beryl"] = function()
  local lines = { "# " .. header }
  for i, c in ipairs(p.terminal) do
    lines[#lines + 1] = ("palette = %d=%s"):format(i - 1, c)
  end
  vim.list_extend(lines, {
    "background = " .. p.bg,
    "foreground = " .. p.fg,
    "cursor-color = " .. p.fg,
    "cursor-text = " .. p.bg,
    "selection-background = " .. p.bg_visual,
    "selection-foreground = " .. p.fg,
    -- 256 色の 16〜255 番を上の 16 色と背景・前景から補間して作る．
    -- オフだと番号で色を指定するツール（pure の 242 など）に xterm 標準の色が出る
    "palette-generate = true",
  })
  return lines
end

